import { afterEach, expect, it, vi } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const mocks = vi.hoisted(() => ({ complete: vi.fn(), stateDir: '' }));
vi.mock('./runtime.js', () => ({ getFeishuRuntime: () => ({state: {resolveStateDir: () => mocks.stateDir}, llm: {complete: mocks.complete}}) }));
import { admitConversationWindow, getConversationWindowStore } from './conversation-window-runtime.js';
import { windowKey } from './conversation-window.js';
afterEach(() => {vi.useRealTimers(); if(mocks.stateDir) rmSync(mocks.stateDir,{recursive:true,force:true}); vi.clearAllMocks();});
it('opens on bare mention, classifies a follow-up with greeting context and renews the window', async () => {
 mocks.stateDir=mkdtempSync(join(tmpdir(),'feishu-window-runtime-'));
 vi.useFakeTimers(); vi.setSystemTime(2000000);
 const message={accountId:'test',chatId:'group',senderOpenId:'user',messageId:'mention',timestamp:Date.now(),text:'',mentionedBot:true,mentionsOthers:false,isBot:false};
 expect(await admitConversationWindow(message,600)).toBe(true);
 expect(mocks.complete).not.toHaveBeenCalled();
 getConversationWindowStore().reply(windowKey(message),message.messageId,'我在，可以查询问题和导出数据，你想做什么？',Date.now());
 vi.setSystemTime(2030000);
 expect(await admitConversationWindow({...message,senderOpenId:'colleague',messageId:'silent',timestamp:Date.now(),text:'补充：任务在测试环境',mentionedBot:false},600)).toBe(false);
 expect(mocks.complete).not.toHaveBeenCalled();
 expect(getConversationWindowStore().get(windowKey(message),Date.now())?.expiresAt).toBe(2600000);
 vi.setSystemTime(2060000);
 mocks.complete.mockResolvedValue({text:'directed'});
 expect(await admitConversationWindow({...message,messageId:'follow',timestamp:Date.now(),text:'帮我导出任务数据',mentionedBot:false},600)).toBe(true);
 const request=mocks.complete.mock.calls[0][0];
 expect(request).toMatchObject({reasoning:'off',maxTokens:256});
 const context=JSON.parse(request.messages[0].content);
 expect(context.recentGroupMessages).toEqual(expect.arrayContaining([expect.objectContaining({senderOpenId:'colleague',text:'补充：任务在测试环境'})]));
 expect(context.recentConversation).toEqual([{role:'user',content:'[用户 @ 助手，发起对话]'},{role:'assistant',content:'我在，可以查询问题和导出数据，你想做什么？'}]);
 expect(getConversationWindowStore().get(windowKey(message),Date.now())?.expiresAt).toBe(2660000);
 mocks.complete.mockResolvedValue({text:''});
 vi.setSystemTime(2120000);
 expect(await admitConversationWindow({...message,messageId:'empty-verdict',timestamp:Date.now(),text:'消息',mentionedBot:false},600)).toBe(false);
 expect(getConversationWindowStore().get(windowKey(message),Date.now())?.expiresAt).toBe(2660000);
});
